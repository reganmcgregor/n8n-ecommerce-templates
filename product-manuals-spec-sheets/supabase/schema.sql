-- Tables for the product manuals and spec sheets template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists documents (
  id integer generated by default as identity primary key,
  product_id text,
  product_title text,
  model text,
  url text,
  source_page text,
  found_via text,
  doc_title text,
  doc_type text,
  label text,
  evidence text,
  status text,
  reason text,
  fingerprint text,
  file_url text,
  mime text,
  size_kb double precision,
  file_id text,
  metaobject_id text,
  slack_channel text,
  slack_ts text,
  found_at timestamptz,
  uploaded_at timestamptz,
  published_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id, url)
);

create table if not exists document_searches (
  id integer generated by default as identity primary key,
  query text,
  product_id text,
  results text,
  cost double precision,
  fetched_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
