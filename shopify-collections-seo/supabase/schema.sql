-- Tables for the Shopify collections SEO template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists collection_proposals (
  id integer generated by default as identity primary key,
  key text,
  kind text,
  source text,
  product_type text,
  vendor text,
  attr_key text,
  attr_value text,
  raw_title text,
  title text,
  handle text,
  keywords text,
  main_keyword text,
  volume double precision,
  live_count double precision,
  score double precision,
  floor double precision,
  sample_titles text,
  rule_set text,
  name_source text,
  skip_reason text,
  status text,
  collection_id text,
  slack_channel text,
  slack_ts text,
  error text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (key)
);
