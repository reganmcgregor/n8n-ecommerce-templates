-- Tables for the ecommerce internal linking template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists link_findings (
  id integer generated by default as identity primary key,
  run_date timestamptz,
  kind text,
  handle text,
  issue text,
  detail text,
  inbound double precision,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists link_changes (
  id integer generated by default as identity primary key,
  run_date timestamptz,
  owner text,
  handle text,
  field text,
  old_value text,
  new_value text,
  status text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
