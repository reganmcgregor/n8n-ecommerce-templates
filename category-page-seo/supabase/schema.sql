-- Tables for the Category page SEO template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists collection_copy (
  id integer generated by default as identity primary key,
  handle text,
  title text,
  keyword text,
  other_searches text,
  volume double precision,
  gid text,
  parent_handle text,
  status text,
  intro text,
  body_html text,
  meta_title text,
  meta_description text,
  flags text,
  reviewed_by text,
  live_html text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (handle)
);

create table if not exists link_audit (
  id integer generated by default as identity primary key,
  run_date timestamptz,
  handle text,
  issue text,
  parent_handle text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
