-- Tables for the automated inventory management template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists offers (
  id integer generated by default as identity primary key,
  source text,
  source_sku text,
  item_id text,
  sku_id text,
  mpn text,
  gtin text,
  brand text,
  title text,
  description text,
  category_raw text,
  product_type text,
  shopify_category_id text,
  ships_from text,
  image_url text,
  raw text,
  freight_method text,
  block_reason text,
  status text,
  reviewed_by text,
  product_id text,
  card_ts text,
  card_nonce text,
  draft_card_ts text,
  cost double precision,
  shipping_cost double precision,
  rrp double precision,
  stock double precision,
  delivery_days double precision,
  est_price double precision,
  missing_since timestamptz,
  discontinued boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (source, source_sku)
);

create table if not exists stock_locations (
  id integer generated by default as identity primary key,
  location_id text,
  name text,
  source text,
  is_active boolean,
  fulfills_online_orders boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (location_id)
);

create table if not exists feed_runs (
  id integer generated by default as identity primary key,
  source text,
  status text,
  reason text,
  rows double precision,
  in_stock double precision,
  run_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists retire_queue (
  id integer generated by default as identity primary key,
  product_id text,
  title text,
  handle text,
  redirect_to text,
  status text,
  decided_by text,
  slack_channel text,
  slack_ts text,
  gone_since timestamptz,
  snooze_until timestamptz,
  decided_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);
