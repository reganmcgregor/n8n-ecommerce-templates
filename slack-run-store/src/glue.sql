-- The conductor: which stage each live product is at, and the last product it enrolled.
create table if not exists store_pipeline (
  id integer generated by default as identity primary key,
  product_id text not null,
  title text,
  stage integer not null default 0,
  stage_name text,
  tags_added text,
  stage_started_at timestamptz not null default now(),
  done boolean not null default false,
  note text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);
create index if not exists store_pipeline_open on store_pipeline (done, stage_started_at);

create table if not exists store_state (
  key text primary key,
  value text,
  "updatedAt" timestamptz not null default now()
);

-- Who ran what from /store, and every decision made on the review page.
create table if not exists store_activity (
  id integer generated by default as identity primary key,
  source text,
  user_id text,
  user_name text,
  action text,
  detail text,
  "createdAt" timestamptz not null default now()
);

-- Buyer guides: one row per collection, the draft waiting in Slack and what went live.
create table if not exists buyer_guides (
  id integer generated by default as identity primary key,
  collection_id text not null,
  handle text,
  title text,
  keyword text,
  volume double precision,
  status text,
  revision integer not null default 0,
  draft_html text,
  draft_text text,
  words integer,
  flags text,
  questions text,
  model text,
  error text,
  slack_channel text,
  slack_ts text,
  decided_by text,
  live_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (collection_id)
);
