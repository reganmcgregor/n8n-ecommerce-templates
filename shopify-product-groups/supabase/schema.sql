-- Tables for the Shopify product groups template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists group_overrides (
  id integer generated by default as identity primary key,
  handle text,
  group_name text,
  option_values text,
  note text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (handle)
);

create table if not exists group_changes (
  id integer generated by default as identity primary key,
  run_date timestamptz,
  action text,
  group_name text,
  product text,
  detail text,
  status text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
