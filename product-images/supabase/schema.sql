-- Tables for the Shopify product images template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists image_queue (
  id integer generated by default as identity primary key,
  product_id text,
  title text,
  vendor text,
  mpn text,
  page_url text,
  status text,
  candidates text,
  current text,
  remove_current boolean,
  card_channel text,
  card_ts text,
  error text,
  report text,
  updated_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);

create table if not exists image_log (
  id integer generated by default as identity primary key,
  product_id text,
  source_hash text,
  media_id text,
  filename text,
  alt text,
  status text,
  pushed_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists brand_domains (
  id integer generated by default as identity primary key,
  brand text,
  domain text,
  url_pattern text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (brand, domain)
);

create table if not exists alt_queue (
  id integer generated by default as identity primary key,
  media_id text,
  product_id text,
  title text,
  image_url text,
  old_alt text,
  new_alt text,
  problems text,
  batch_id text,
  status text,
  updated_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
