create table if not exists instagram_posts (
  id integer generated by default as identity primary key,
  product_id text,
  product_title text,
  handle text,
  headline text,
  product_line text,
  caption text,
  alt_text text,
  source_image text,
  photo_kind text,
  image_url text,
  shopify_file_id text,
  link text,
  problems text,
  status text,
  slack_channel text,
  slack_ts text,
  decided_by text,
  decided_at timestamptz,
  scheduled_for timestamptz,
  container_id text,
  media_id text,
  post_url text,
  posted_at timestamptz,
  error text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create table if not exists instagram_token (
  id integer generated by default as identity primary key,
  account text,
  token text,
  ig_user_id text,
  username text,
  expires_at timestamptz,
  refreshed_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create unique index if not exists instagram_posts_product on instagram_posts (product_id);
create index if not exists instagram_posts_status on instagram_posts (status);
create unique index if not exists instagram_token_account on instagram_token (account);
