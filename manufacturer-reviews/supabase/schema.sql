-- Tables for the Manufacturer reviews template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists review_sites (
  id integer generated by default as identity primary key,
  brand text,
  domain text,
  source_name text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create table if not exists review_sources (
  id integer generated by default as identity primary key,
  product_id text,
  product_title text,
  product_handle text,
  brand text,
  model text,
  url text,
  source_name text,
  found_by text,
  status text,
  reader text,
  page_title text,
  stated_count double precision,
  review_count double precision,
  average double precision,
  stars text,
  left_out text,
  error text,
  attempts double precision,
  checked_at timestamptz,
  card_channel text,
  card_ts text,
  card text,
  decided_by text,
  decided_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create table if not exists reviews (
  id integer generated by default as identity primary key,
  key text,
  source_id double precision,
  product_id text,
  product_handle text,
  review_id text,
  rating double precision,
  review_date text,
  reviewer_name text,
  row text,
  status text,
  batch_id text,
  found_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create table if not exists review_batches (
  id integer generated by default as identity primary key,
  batch_id text,
  status text,
  review_count double precision,
  product_count double precision,
  card_channel text,
  card_ts text,
  card text,
  delivered_at timestamptz,
  imported_by text,
  imported_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create unique index if not exists review_sites_brand_domain on review_sites (lower(brand), domain);
create index if not exists review_sources_product on review_sources (product_id);
create unique index if not exists reviews_key on reviews (key);
create index if not exists reviews_status on reviews (status, source_id);
create index if not exists reviews_batch on reviews (batch_id);
