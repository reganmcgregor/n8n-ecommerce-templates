-- Tables for the n8n workflow monitoring template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists monitor_failures (
  id integer generated by default as identity primary key,
  workflow_id text,
  workflow_name text,
  execution_id text,
  execution_url text,
  node_name text,
  error_message text,
  mode text,
  failed_at timestamptz,
  alerted boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create index if not exists monitor_failures_0 on monitor_failures (workflow_id, failed_at);
create index if not exists monitor_failures_1 on monitor_failures (failed_at);
create table if not exists monitor_runs (
  id integer generated by default as identity primary key,
  workflow_id text,
  workflow_name text,
  items integer,
  note text,
  ran_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create index if not exists monitor_runs_0 on monitor_runs (workflow_id, ran_at);
create table if not exists monitor_watch (
  id integer generated by default as identity primary key,
  workflow_id text unique not null,
  workflow_name text,
  schedule text,
  max_gap_minutes integer,
  override_gap_minutes integer,
  min_items integer,
  empty_runs_before_alert integer,
  enabled boolean,
  alerting boolean,
  alert_kind text,
  last_alert_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
