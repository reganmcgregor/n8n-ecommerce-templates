-- Slack slash command: the run log.
-- Run once in Supabase's SQL editor, or run the workflow's "Run once to set up".
-- /store status reads the approvals table from the Slack approvals template
-- (slack-approval-workflow-n8n/supabase/schema.sql); create that first if you use status.

create table if not exists command_runs (
  id integer generated by default as identity primary key,
  job text,
  args text,
  user_id text,
  user_name text,
  result text,         -- finished | failed
  seconds integer,
  error text,
  created_at timestamptz not null default now()
);

