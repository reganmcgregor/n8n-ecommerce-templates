-- Tables for the Add products to Shopify template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists offers (
  id integer generated by default as identity primary key,
  source text,
  source_sku text,
  item_id text,
  sku_id text,
  mpn text,
  gtin text,
  brand text,
  title text,
  description text,
  category_raw text,
  product_type text,
  shopify_category_id text,
  ships_from text,
  image_url text,
  raw text,
  freight_method text,
  block_reason text,
  status text,
  reviewed_by text,
  product_id text,
  card_ts text,
  card_nonce text,
  draft_card_ts text,
  cost double precision,
  shipping_cost double precision,
  rrp double precision,
  stock double precision,
  delivery_days double precision,
  est_price double precision,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (source, source_sku)
);

create table if not exists category_map (
  id integer generated by default as identity primary key,
  source text,
  match_field text,
  pattern text,
  product_type text,
  shopify_category_id text,
  action text,
  reason text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists aliexpress_items (
  id integer generated by default as identity primary key,
  item_id text,
  sku_id text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists aliexpress_auth (
  id integer generated by default as identity primary key,
  app_key text,
  access_token text,
  refresh_token text,
  access_expires_at text,
  refresh_expires_at text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
