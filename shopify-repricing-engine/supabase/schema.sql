-- Tables for the Shopify repricing engine template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists pricing_rules (
  id integer generated by default as identity primary key,
  product_type text,
  margin_floor_pct double precision,
  cost_plus_multiplier double precision,
  fee_pct double precision,
  fee_fixed double precision,
  undercut_amount double precision,
  cost_change_pct double precision,
  notes text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_type)
);

create table if not exists price_decisions (
  id integer generated by default as identity primary key,
  variant_id text,
  product_id text,
  sku text,
  title text,
  product_type text,
  product_status text,
  rule text,
  flags text,
  status text,
  explanation text,
  competitor_name text,
  competitor_url text,
  decided_by text,
  slack_channel text,
  slack_ts text,
  error text,
  current_price double precision,
  cost double precision,
  last_cost double precision,
  rrp double precision,
  competitor_price double precision,
  floor_price double precision,
  target double precision,
  proposed_price double precision,
  move_pct double precision,
  profit double precision,
  held_price double precision,
  card_price double precision,
  locked boolean,
  competitor_checked_at timestamptz,
  calculated_at timestamptz,
  decided_at timestamptz,
  applied_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (variant_id)
);

create table if not exists price_changes (
  id integer generated by default as identity primary key,
  variant_id text,
  product_id text,
  title text,
  rule text,
  source text,
  run_id text,
  changed_by text,
  from_price double precision,
  to_price double precision,
  move_pct double precision,
  changed_at timestamptz,
  reverted boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists pricing_runs (
  id integer generated by default as identity primary key,
  run_id text,
  scope text,
  started_at timestamptz,
  variants double precision,
  changes_due double precision,
  changed double precision,
  floor_fixes double precision,
  held double precision,
  failed double precision,
  no_cost double precision,
  stale_listings double precision,
  carried_over double precision,
  stopped boolean,
  stop_reason text,
  dry_run boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
