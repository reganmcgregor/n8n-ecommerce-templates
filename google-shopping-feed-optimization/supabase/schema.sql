-- Tables for the Google Shopping feed optimisation template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists feed_fields (
  id integer generated by default as identity primary key,
  channel text,
  sort_order double precision,
  field text,
  kind text,
  target text,
  source text,
  required boolean,
  rule text,
  static_value text,
  active boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (channel, field)
);

create table if not exists feed_status (
  id integer generated by default as identity primary key,
  product_id text,
  state text,
  missing text,
  app_fields text,
  sent text,
  google_state text,
  google_issues text,
  slack_channel text,
  slack_ts text,
  checked_at timestamptz,
  read_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);
