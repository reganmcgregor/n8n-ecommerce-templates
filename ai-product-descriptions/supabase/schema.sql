-- Tables for the AI product descriptions template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists description_drafts (
  id integer generated by default as identity primary key,
  product_id text,
  title text,
  category text,
  old_intro text,
  intro_mode text,
  draft_text text,
  final_text text,
  flags text,
  words double precision,
  model text,
  status text,
  error text,
  edited boolean,
  html text,
  slack_channel text,
  slack_ts text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);

create table if not exists description_examples (
  id integer generated by default as identity primary key,
  category text,
  text text,
  source text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create unique index if not exists description_examples_text_key on description_examples (md5(text));

create table if not exists source_pages (
  id integer generated by default as identity primary key,
  url text,
  focused_text text,
  fetched_at text,
  status text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (url)
);
