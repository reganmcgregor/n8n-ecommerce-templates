-- Tables for the AI product titles template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists title_examples (
  id integer generated by default as identity primary key,
  category text,
  input text,
  title text,
  source text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (title)
);

create table if not exists title_drafts (
  id integer generated by default as identity primary key,
  product_id text,
  category text,
  input text,
  old_title text,
  new_title text,
  title_source text,
  problems text,
  status text,
  slack_ts text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);
