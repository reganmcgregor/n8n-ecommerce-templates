-- Tables for the Shopify product videos template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists brand_channels (
  id integer generated by default as identity primary key,
  vendor text,
  handle text,
  channel_id text,
  channel_name text,
  domains text,
  url_pattern text,
  note text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create table if not exists video_candidates (
  id integer generated by default as identity primary key,
  product_id text,
  product_title text,
  model text,
  video_id text,
  url text,
  title text,
  channel_id text,
  channel_name text,
  is_manufacturer boolean,
  duration_s double precision,
  views double precision,
  published_at timestamptz,
  language text,
  match_quote text,
  match_source text,
  video_type text,
  coverage text,
  status text,
  card_channel text,
  card_ts text,
  card text,
  metaobject_id text,
  decided_by text,
  decided_at timestamptz,
  error text,
  found_at timestamptz,
  checked_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create table if not exists video_runs (
  id integer generated by default as identity primary key,
  product_id text,
  product_title text,
  model text,
  ran_at timestamptz,
  searches double precision,
  quota_units double precision,
  found double precision,
  kept double precision,
  dropped text,
  error text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create unique index if not exists video_candidates_product_video on video_candidates (product_id, video_id);
create index if not exists video_candidates_status on video_candidates (status);
create index if not exists video_runs_product on video_runs (product_id, ran_at);
