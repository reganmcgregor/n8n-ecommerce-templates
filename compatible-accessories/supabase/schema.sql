-- Tables for the compatible accessories template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists accessory_sources (
  id integer generated by default as identity primary key,
  accessory_id text,
  url text,
  kind text,
  found_via text,
  text text,
  hash text,
  fetched_at text,
  status text,
  error text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (accessory_id, url)
);

create table if not exists accessory_reviews (
  id integer generated by default as identity primary key,
  accessory_id text,
  title text,
  model text,
  revision double precision,
  status text,
  source_hash text,
  candidates text,
  matches text,
  rejected text,
  model_used text,
  error text,
  slack_channel text,
  slack_ts text,
  decided_by text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (accessory_id)
);

create table if not exists accessory_matches (
  id integer generated by default as identity primary key,
  accessory_id text,
  accessory_title text,
  target_id text,
  target_title text,
  target_model text,
  revision double precision,
  status text,
  reason text,
  quote text,
  source_url text,
  decided_by text,
  slack_channel text,
  slack_ts text,
  error text,
  pushed_at text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (accessory_id, target_id)
);
