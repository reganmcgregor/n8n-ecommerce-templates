create table if not exists pins (
  id integer generated by default as identity primary key,
  product_id text,
  product_title text,
  handle text,
  pin_no integer,
  pin_kind text,
  board_key text,
  board_name text,
  board_id text,
  title text,
  description text,
  alt_text text,
  headline text,
  product_line text,
  review_quote text,
  review_rating integer,
  review_author text,
  review_source text,
  image_url text,
  source_image text,
  photo_kind text,
  shopify_file_id text,
  link text,
  problems text,
  status text,
  slack_channel text,
  slack_ts text,
  decided_by text,
  decided_at timestamptz,
  post_id text,
  scheduled_for timestamptz,
  posted_at timestamptz,
  pin_url text,
  error text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create table if not exists pin_reviews (
  id integer generated by default as identity primary key,
  product_handle text,
  rating integer,
  quote text,
  author text,
  source text,
  verified boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
create unique index if not exists pins_product_image on pins (product_id, pin_kind, source_image);
create index if not exists pins_status on pins (status);
create index if not exists pin_reviews_handle on pin_reviews (product_handle);
