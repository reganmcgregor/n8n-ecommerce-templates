-- Tables for the AI product FAQs template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists faq_drafts (
  id integer generated by default as identity primary key,
  product_id text,
  title text,
  model text,
  product_type text,
  revision double precision,
  status text,
  faqs text,
  rejected text,
  source_hash text,
  sources text,
  model_used text,
  error text,
  slack_channel text,
  slack_ts text,
  decided_by text,
  published_ids text,
  product_url text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);

create table if not exists faq_sources (
  id integer generated by default as identity primary key,
  product_id text,
  url text,
  kind text,
  label text,
  found_via text,
  text text,
  hash text,
  fetched_at text,
  status text,
  error text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id, url)
);

create table if not exists faq_questions (
  id integer generated by default as identity primary key,
  product_type text,
  product_id text,
  question text,
  source text,
  status text,
  email text,
  ip_hash text,
  slack_channel text,
  slack_ts text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_type, product_id, question)
);
