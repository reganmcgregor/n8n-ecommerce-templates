-- Tables for the Shopify collection sorting template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists collection_sort (
  id integer generated by default as identity primary key,
  handle text,
  gid text,
  title text,
  keyword text,
  other_searches text,
  mode text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (handle)
);

create table if not exists title_vectors (
  id integer generated by default as identity primary key,
  text text,
  vector text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (text)
);
