-- Table for the Slack approvals template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists approvals (
  id integer generated by default as identity primary key,
  kind text,
  item_id text,
  item_label text,
  current_value text,
  proposed_value text,
  final_value text,
  context text,
  status text,
  channel text,
  ts text,
  requested_at timestamptz,
  decided_by text,
  decided_at timestamptz,
  reason text,
  apply_workflow_id text,
  reminded_at timestamptz,
  snooze_until timestamptz,
  max_length integer,
  must_include text,
  card text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now());
create index if not exists approvals_item on approvals (item_id, kind);
create index if not exists approvals_status on approvals (status);
