-- Tables for the Product data enrichment template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists attribute_schema (
  id integer generated by default as identity primary key,
  category text,
  key text,
  label text,
  type text,
  unit text,
  allowed text,
  standard text,
  standard_map text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (category, key)
);

create table if not exists extract_runs (
  id integer generated by default as identity primary key,
  product_id text,
  title text,
  sources text,
  spec_status text,
  error text,
  values_found numeric,
  auto_approved numeric,
  to_review numeric,
  extracted_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id)
);

create table if not exists attribute_values (
  id integer generated by default as identity primary key,
  product_id text,
  product_title text,
  category text,
  category_id text,
  key text,
  value text,
  source text,
  source_url text,
  evidence text,
  review_status text,
  push_status text,
  push_error text,
  reviewed_by text,
  slack_channel text,
  slack_ts text,
  confidence numeric,
  valid boolean,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_id, key, value)
);

create table if not exists taxonomy_values (
  id integer generated by default as identity primary key,
  category_id text,
  standard_key text,
  value text,
  taxonomy_value_gid text,
  metaobject_gid text,
  status text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
