-- Tables for the Competitor price monitoring template (Supabase / Postgres).
-- Run once in the Supabase SQL editor, or let the Setup lane run it.

create table if not exists competitor_listings (
  id integer generated by default as identity primary key,
  listing_key text,
  product_key text,
  sku text,
  mpn text,
  gtin text,
  product_title text,
  url text,
  domain text,
  seller text,
  listing_title text,
  matched_by text,
  confidence double precision,
  last_price double precision,
  currency text,
  in_stock boolean,
  status text,
  method text,
  last_checked_at timestamptz,
  last_change double precision,
  pending_price double precision,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (listing_key)
);

create table if not exists competitor_prices (
  id integer generated by default as identity primary key,
  listing_key text,
  product_key text,
  domain text,
  price double precision,
  in_stock boolean,
  method text,
  captured_at timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists competitor_searches (
  id integer generated by default as identity primary key,
  product_key text,
  query text,
  last_searched_at timestamptz,
  listings_found double precision,
  rejected double precision,
  cost_usd double precision,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  unique (product_key)
);
